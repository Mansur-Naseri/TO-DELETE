race = input("what is your race?. please choose from: European, American, Asia, African, South American. Australian.")

if race == "European":
    print("you are European")
elif race == "American":
    print("you are American")
elif race == "Asia":
    print("you are Asia")
elif race == "African":
    print("you are African")
elif race == "South American":
    print("you are South American")
elif race == "Australian":
    print("you are Australian")
else: print("no match")